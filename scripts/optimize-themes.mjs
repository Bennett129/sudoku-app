/**
 * Builds web-ready theme backgrounds from the full-size originals.
 *
 *   assets/themes/<id>.jpg   originals (≈19 MB total, git-ignored)
 *     → public/themes/<id>-1200.avif   phones (covers 390 px @3x)
 *     → public/themes/<id>-2400.avif   tablets / desktop / retina
 *     → public/themes/<id>-1200.jpg    fallback for browsers without AVIF
 *     → src/app/theme-placeholders.css tiny blurred previews, inlined so
 *                                       something paints before the photo loads
 *
 * Run: npm run themes
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "assets/themes");
const outDir = path.join(root, "public/themes");
const cssOut = path.join(root, "src/app/theme-placeholders.css");

const kb = (bytes) => `${Math.round(bytes / 1024)} KB`;

await mkdir(outDir, { recursive: true });
const ids = (await readdir(srcDir)).filter((f) => f.endsWith(".jpg")).map((f) => f.slice(0, -4)).sort();
if (ids.length === 0) throw new Error(`No .jpg originals in ${srcDir}`);

let css = "/* Generated by scripts/optimize-themes.mjs — do not edit. */\n";

for (const id of ids) {
  const src = sharp(path.join(srcDir, `${id}.jpg`)).rotate(); // respect EXIF orientation
  const outputs = [
    ["1200.avif", (s) => s.resize({ width: 1200 }).avif({ quality: 55, effort: 6 })],
    ["2400.avif", (s) => s.resize({ width: 2400 }).avif({ quality: 50, effort: 6 })],
    ["1200.jpg", (s) => s.resize({ width: 1200 }).jpeg({ quality: 78, mozjpeg: true, progressive: true })],
  ];
  const sizes = [];
  for (const [suffix, encode] of outputs) {
    const info = await encode(src.clone()).toFile(path.join(outDir, `${id}-${suffix}`));
    sizes.push(`${suffix} ${kb(info.size)}`);
  }

  const tiny = await src.clone().resize({ width: 24 }).blur(1).webp({ quality: 40 }).toBuffer();
  css += `[data-theme="${id}"] { --bg-placeholder: url("data:image/webp;base64,${tiny.toString("base64")}"); }\n`;
  console.log(`${id}: ${sizes.join(" · ")} · placeholder ${tiny.length} B`);
}

await writeFile(cssOut, css);
console.log(`wrote ${path.relative(root, cssOut)}`);
